/// Render `stitch/stitch.toml` from the corridors and the current regimes.
///
/// Stitch reads its config only at startup (its ADVANCED.md: "restart the
/// process after any change"), so a regime change is: rewrite this file, then
/// run STITCH_RESTART_CMD (e.g. `systemctl restart stitch`). `shock` needs
/// neither — the feed withholds the price and Stitch stops on its own.
///
/// Field names follow textile-stitch's stitch.example.toml. Check them against
/// the version you install before going live; a misspelt key is silently
/// ignored by most TOML readers, which here would mean quoting at a default.

import { CORRIDORS, type CorridorId, RPC, TEXTILE, USDT } from "./config.ts";
import { EFFECTS, type Regime } from "./regime.ts";

const atomic = (amount: number, decimals: number) =>
  BigInt(Math.floor(amount * 10 ** Math.min(decimals, 6))) * 10n ** BigInt(Math.max(0, decimals - 6));

export function renderStitch(regimes: Partial<Record<CorridorId, Regime>>, feedBase: string): string {
  const pools = (Object.keys(CORRIDORS) as CorridorId[]).map((id) => {
    const c = CORRIDORS[id];
    const fx = EFFECTS[regimes[id] ?? "calm"];
    const offset = Math.round(c.baseOffsetBps * fx.offsetMultiplier);
    // In shock the share is 0; keep a 1-unit floor so the TOML stays valid —
    // the feed is what actually stops quoting.
    const buyCap = atomic(Math.max(c.buyCapUsdt * fx.liquidityShare, 1), USDT.decimals);
    const sellCap = atomic(Math.max(c.sellCapLocal * fx.liquidityShare, 1), c.token.decimals);
    return `
# ${c.token.symbol} / USDT — regime: ${regimes[id] ?? "calm"}
[[pools]]
feed_url = "${feedBase}/feed/${id}"
collateral = "${c.token.address}"
collateral_decimals = ${c.token.decimals}
debt = "${USDT.address}"
debt_decimals = ${USDT.decimals}

buy_offset_bps = ${offset}
buy_total_liquidity_debt = "${buyCap}"
buy_min_slice_debt = "${atomic(1, USDT.decimals)}"
buy_max_orders = 10

sell_offset_bps = ${offset}
sell_total_liquidity_collateral = "${sellCap}"
sell_min_slice_debt = "${atomic(1, USDT.decimals)}"
sell_max_orders = 10
`;
  });

  return `# GENERATED by Cambio (src/stitchconf.ts) — do not edit by hand.
# Regime changes rewrite this file; Stitch reads it only at startup.
chain_id = 42220
rpc_url = "${RPC}"
indexer_url = "${TEXTILE.indexer}"
permit2 = "${TEXTILE.permit2}"
reactor = "${TEXTILE.reactor}"
tick_interval_secs = 5
book_enabled = false

[feed]
# Short on purpose: when the feed withholds a price (sources disagree, a news
# shock, the daily loss limit), quotes must lapse within seconds.
staleness_secs = 20
${pools.join("")}`;
}
